def base_must(extra):
    return list(COMMON_MUST) + list(extra)

def base_forbid(extra=None):
    return list(COMMON_FORBID) + list(extra or [])

def shots_pref(types_and_notes=""):
    """placeholder; renderer fills 优先 from 选镜单 counts."""
    return types_and_notes

