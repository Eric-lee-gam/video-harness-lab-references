# ---------- helpers for recurring musts ----------
def must_pi(space=None, substrate=True, material=True):
    xs = [
        item("画面类型", vcode("施工·批刮覆盖"), note="总纲 B1"),
        item("主动作", "批刮", note=ACTION_NOTE_PI),
        item("阶段", "上料施工中", note="总纲一致性：批刮覆盖必须是上料施工中"),
        item("动作完整", "有起有收", note="落刀到收刀尽量完整，不要只切中段"),
    ]
    if space:
        xs.append(item("空间", space))
    if substrate:
        xs.append(item("基层", "旧瓷砖且砖缝可见（优先）或能同时看见基层与新材料", note="「在瓷砖上直接批刮」类句子需要看见刀下砖缝"))
    if material:
        xs.append(item("材料类目", "微陶泥", note="词表已确认金刚泥/金刚陶泥/陶砂均归微陶泥；依据须到人工确认或目录标称，质感判断不够；镜序只认已确认时段"))
        xs.append(item("材料依据等级", "人工确认 或 目录标称"))
    return xs

def must_finish(space=None, with_people=False):
    if with_people:
        xs = [
            item("画面类型", vcode("成品里的人") + " 或 " + vcode("成品空间"), note="有人在做完的空间里用成品里的人；空镜用成品空间"),
            item("阶段", "完工空房 或 入住使用"),
        ]
    else:
        xs = [
            item("画面类型", vcode("成品空间"), note="总纲：无人且面层做完"),
            item("人数", "0", note="成品空间人数必须为 0"),
            item("阶段", "完工空房 或 入住使用"),
        ]
    if space:
        xs.append(item("空间", space))
    return xs

def must_person_cam():
    return [
        item("画面类型", vcode("人物对镜头"), note="看着镜头讲话的人是画面主体，不论在成品房还是工地"),
        item("人数", "至少 1"),
        item("朝向", "看镜头"),
        item("动作完整", "有起有收", note="手势或抬头看镜要完整"),
    ]

def must_handshake():
    return [
        item("画面类型", vcode("握手/与客户沟通"), note="已在屋里站定握手、交谈、一起看一样东西；进门搬东西算团队上门，不要混"),
        item("主动作", "握手 或 交谈讲解"),
        item("人数", "至少 2（优先能看出沟通关系）"),
    ]

